pub fn generated_wire_typescript() -> String {
    // P0b guardrail: `assert_contract_shapes` makes add/remove drift for public
    // contract fields and enum variants fail to compile, but serde attributes
    // are still hand-encoded below. Rename/default/nullability changes and new
    // tagged FieldValue/CustomFieldValue variants need explicit fixture coverage.
    assert_contract_shapes();
    let mut output = generated_header("mise run generate:contracts");
    render_contract_wire_types(&mut output);
    trim_extra_terminal_blank_line(&mut output);
    output
}

pub struct AppClientSpec<'a> {
    pub command: &'a str,
    pub app_id: &'a str,
    pub customer_id: &'a str,
    pub schema: &'a Schema,
    pub default_actor_id: &'a str,
    pub include_model_field_aliases: bool,
    pub include_draft_apply: bool,
    pub typescript_extra_types_before_visible_record: &'a str,
    pub typescript_extra_types_after_visible_record: &'a str,
    pub typescript_http_mode: TypeScriptHttpMode<'a>,
    pub typescript_extra_before_read_json_response: &'a str,
    pub javascript_runtime_before_helpers: &'a str,
    pub javascript_runtime_after_apply: &'a str,
}

#[derive(Clone, Copy)]
pub enum TypeScriptHttpMode<'a> {
    Plain,
    ConfigurableBasePath {
        options_type: &'a str,
        configure_function: &'a str,
        state_variable: &'a str,
    },
}

pub fn generated_app_typescript(spec: &AppClientSpec<'_>) -> String {
    assert_contract_shapes();

    let mut output = generated_header(spec.command);
    render_app_schema_constants(&mut output, spec.schema, false);
    render_app_wire_types(&mut output, spec);
    append_trimmed_block(
        &mut output,
        spec.typescript_extra_types_before_visible_record,
    );
    render_visible_record_type(&mut output, "string", "string");
    append_trimmed_block(
        &mut output,
        spec.typescript_extra_types_after_visible_record,
    );
    render_typescript_http_helpers(&mut output, spec);
    append_trimmed_block(&mut output, spec.typescript_extra_before_read_json_response);
    render_typescript_read_json_response(&mut output);
    render_typescript_apply_helpers(&mut output, spec);
    output
}

pub fn generated_app_javascript(spec: &AppClientSpec<'_>) -> String {
    let mut output = generated_header(spec.command);
    render_app_schema_constants(&mut output, spec.schema, true);
    append_trimmed_block(&mut output, spec.javascript_runtime_before_helpers);
    render_javascript_value_helpers(&mut output, spec);
    append_trailing_runtime_block(&mut output, spec.javascript_runtime_after_apply);
    output
}

fn generated_header(command: &str) -> String {
    format!("// Generated by `{command}`.\n// Do not edit by hand.\n\n")
}

