fn render_typescript_http_helpers(output: &mut String, spec: &AppClientSpec<'_>) {
    let fetch_path = match spec.typescript_http_mode {
        TypeScriptHttpMode::Plain => "path".to_string(),
        TypeScriptHttpMode::ConfigurableBasePath {
            options_type,
            configure_function,
            state_variable,
        } => {
            output.push_str(&format!(
                "export type {options_type} = {{\n  apiBasePath?: string | null;\n}};\n\n"
            ));
            output.push_str(&format!("let {state_variable} = \"\";\n\n"));
            output.push_str(&format!(
                "export function {configure_function}(options: {options_type} = {{}}): void {{\n"
            ));
            output.push_str(&format!(
                "  {state_variable} = normalizeApiBasePath(options.apiBasePath);\n"
            ));
            output.push_str("}\n\n");
            output.push_str("export function resolveApiPath(path: string): string {\n");
            output.push_str(&format!(
                "  if (!{state_variable} || !path.startsWith(\"/api\")) return path;\n"
            ));
            output.push_str(&format!(
                "  if (path === \"/api\") return {state_variable};\n"
            ));
            output.push_str(&format!(
                "  if (path.startsWith(\"/api/\")) return `${{{state_variable}}}${{path.slice(4)}}`;\n"
            ));
            output.push_str("  return path;\n");
            output.push_str("}\n\n");
            output.push_str(
                "function normalizeApiBasePath(value: string | null | undefined): string {\n",
            );
            output.push_str("  if (!value) return \"\";\n");
            output.push_str("  const trimmed = value.trim().replace(/\\/+$/, \"\");\n");
            output.push_str("  if (!trimmed || trimmed === \"/api\") return \"\";\n");
            output.push_str("  return trimmed.startsWith(\"/\") ? trimmed : `/${trimmed}`;\n");
            output.push_str("}\n\n");
            "resolveApiPath(path)".to_string()
        }
    };

    output.push_str(
        "export async function postJson<T>(\n  path: string,\n  body: unknown,\n  init: { signal?: AbortSignal } = {},\n): Promise<T> {\n",
    );
    output.push_str(&format!(
        "  const response = await fetch({fetch_path}, {{\n"
    ));
    output.push_str("    method: \"POST\",\n");
    output.push_str("    headers: { \"content-type\": \"application/json\" },\n");
    output.push_str("    body: JSON.stringify(body),\n");
    output.push_str("    signal: init.signal,\n");
    output.push_str("  });\n");
    output.push_str("  const payload = await readJsonResponse(response);\n");
    output.push_str("  if (!response.ok) {\n");
    output.push_str("    throw payload;\n");
    output.push_str("  }\n");
    output.push_str("  return payload as T;\n");
    output.push_str("}\n\n");

    output.push_str("export async function getJson<T>(path: string): Promise<T> {\n");
    output.push_str(&format!("  const response = await fetch({fetch_path});\n"));
    output.push_str("  const payload = await readJsonResponse(response);\n");
    output.push_str("  if (!response.ok) {\n");
    output.push_str("    throw payload;\n");
    output.push_str("  }\n");
    output.push_str("  return payload as T;\n");
    output.push_str("}\n\n");
}

fn render_typescript_read_json_response(output: &mut String) {
    output.push_str("async function readJsonResponse(response: Response): Promise<unknown> {\n");
    output.push_str("  const text = await response.text();\n");
    output.push_str("  if (text.length === 0) return null;\n");
    output.push_str("  try {\n");
    output.push_str("    return JSON.parse(text);\n");
    output.push_str("  } catch (error) {\n");
    output.push_str("    throw {\n");
    output.push_str("      code: \"invalid_json_response\",\n");
    output
        .push_str("      message: `Expected JSON response from ${response.url || \"request\"}`,\n");
    output.push_str("      details: [\n");
    output.push_str("        {\n");
    output.push_str("          path: \"response\",\n");
    output.push_str("          code: \"invalid_json_response\",\n");
    output.push_str("          message: error instanceof Error ? error.message : String(error),\n");
    output.push_str("        },\n");
    output.push_str("      ],\n");
    output.push_str("    };\n");
    output.push_str("  }\n");
    output.push_str("}\n\n");
}

